"use strict";

(function installAplCartWarningStackBridge(root, factory) {
  const extendLibrary = factory();
  if (typeof module !== "undefined" && module.exports) module.exports = extendLibrary;
  if (root?.ServoForgeTroubleshootingLibrary) root.ServoForgeTroubleshootingLibrary = extendLibrary(root.ServoForgeTroubleshootingLibrary);
})(typeof globalThis !== "undefined" ? globalThis : this, function createAplCartWarningStackBridgeExtension() {
  return function extendLibrary(base) {
    if (!base?.analyzeTopModulFaultStack || !base?.getEntry || !base?.searchEntries || !base?.getAplCartWarningPlan) {
      throw new Error("v365 APL Cart warnings and the TopModul alarm-stack analyzer are required before v366 mixed chronology.");
    }

    const ROLE_LABELS = Object.freeze({
      ...(base.topModulAlarmStackRoles || {}),
      "cart-fault": "Cart-local fault",
      "pre-fault-warning": "Source-backed pre-fault warning",
      "warning-state": "Source-backed warning / state",
      "operating-warning": "Operating-state warning",
      "warning-source-gap": "Warning source gap / inactive path"
    });

    const ROLE_PRIORITY = Object.freeze({
      "cart-fault": 20,
      "pre-fault-warning": 24,
      "warning-state": 34,
      "operating-warning": 66,
      "warning-source-gap": 100
    });

    const WARNING_LINKS = Object.freeze({
      5: Object.freeze({ targetCode: "00025", kind: "pre-fault", reason: "W 0005 Low Labels is generated by the selected end-of-reel condition while Cart Fault 00025 is still clear; 00025 is the later No Labels / End Of Reel escalation." }),
      8: Object.freeze({ targetCode: "00020", kind: "state-sequence", reason: "W 0008 is the current P133 carriage-not-front state; Cart Fault 00020 is the separate stored return-to-front/reset-required state after the carriage has been away." }),
      12: Object.freeze({ targetCode: "00022", kind: "pre-fault", reason: "W 0012 latches on label-length MeasureError; repeated bad measurements can later latch Cart Fault 00022 through the source-configured count criterion." }),
      15: Object.freeze({ targetCode: "00014", kind: "companion", reason: "W 0015 is the current !ReadyForETHConnect_L3 state while Cart Fault 00014 is the separate latched base-machine communication fault." })
    });

    const compact = (value) => String(value || "").trim().replace(/\s+/g, " ");
    const entryCode = (entry) => String(entry?.code || (Number.isFinite(Number(entry?.number)) ? entry.number : ""));
    const isWarning = (entry) => Number.isFinite(Number(entry?.warningNumber)) && /^apl-cart-warning-/i.test(String(entry?.id || ""));
    const isFiveDigitCartFault = (entry) => /^\d{5}$/.test(String(entry?.code || "")) && /^apl-cart-|^topmodul-00067/i.test(String(entry?.id || ""));

    function extractMixedTokens(input) {
      if (Array.isArray(input)) return input.map(compact).filter(Boolean);
      const text = compact(input);
      if (!text) return [];
      const explicit = String(input || "").match(/\bW\s*0*\d{1,2}\b|\b\d{5}\b|\b\d{3,4}\b/gi) || [];
      if (explicit.length) return explicit.map(compact);
      return String(input || "").split(/[\n,;>|→]+/).map(compact).filter(Boolean);
    }

    function resolveWarning(raw) {
      const match = /\bW\s*0*(\d{1,2})\b/i.exec(raw);
      if (!match) return null;
      const number = Number(match[1]);
      return base.getEntry(`apl-cart-warning-${String(number).padStart(4, "0")}`) || null;
    }

    function resolveFiveDigit(raw, context) {
      if (!/^\d{5}$/.test(raw)) return null;
      if (raw === "00067") {
        return base.searchEntries("00067", { ...context, machineType: context.machineType || "TopModul", applicationMode: context.applicationMode || "apl" }, 8)
          .find((entry) => entry?.id === "topmodul-00067-labeler-encoder-feedback") || null;
      }
      const exact = base.searchEntries(raw, { ...context, machineType: context.machineType || "TopModul", applicationMode: context.applicationMode || "apl" }, 12)
        .find((entry) => String(entry?.code || "") === raw && /^apl-cart-/i.test(String(entry?.id || "")));
      return exact || null;
    }

    function resolveToken(token, context = {}) {
      const raw = compact(token);
      if (!raw) return null;
      const warning = resolveWarning(raw);
      if (warning) return warning;
      const cart = resolveFiveDigit(raw, context);
      if (cart) return cart;
      if (/^\d{3,4}$/.test(raw) && base.getTopModulFault) {
        const fault = base.getTopModulFault(Number(raw));
        if (fault) return fault;
      }
      return base.searchEntries(raw, { ...context, machineType: context.machineType || "TopModul" }, 5)[0] || null;
    }

    function baseStackItem(entry, token, context) {
      if (isWarning(entry) || isFiveDigitCartFault(entry) && entry.id !== "topmodul-00067-labeler-encoder-feedback") return null;
      const query = entry.id === "topmodul-00067-labeler-encoder-feedback" ? "00067" : (entry.code || token);
      try {
        return base.analyzeTopModulFaultStack(query, context)?.observed?.find((item) => item.entry?.id === entry.id) || null;
      } catch (_) {
        return null;
      }
    }

    function warningRole(entry) {
      const number = Number(entry.warningNumber);
      if (entry.sourceGap) return "warning-source-gap";
      if ([5, 12].includes(number)) return "pre-fault-warning";
      if ([4, 10, 13].includes(number)) return "operating-warning";
      return "warning-state";
    }

    function classify(entry, token, context) {
      if (isWarning(entry)) {
        const role = warningRole(entry);
        return { role, roleLabel: ROLE_LABELS[role], priority: ROLE_PRIORITY[role] };
      }
      const inherited = baseStackItem(entry, token, context);
      if (inherited) return { role: inherited.role, roleLabel: inherited.roleLabel, priority: inherited.priority };
      if (isFiveDigitCartFault(entry)) {
        const role = entry.sourceGap ? "source-gap" : "cart-fault";
        return { role, roleLabel: ROLE_LABELS[role] || (role === "source-gap" ? "Source gap" : "Cart-local fault"), priority: role === "source-gap" ? 100 : ROLE_PRIORITY["cart-fault"] };
      }
      return { role: entry.sourceGap ? "source-gap" : "catalog-only", roleLabel: entry.sourceGap ? "Source gap" : "Catalog-only binding", priority: entry.sourceGap ? 100 : 82 };
    }

    function copyBaseRelations(observed, context) {
      const eligible = observed.filter((item) => !isWarning(item.entry) && (!isFiveDigitCartFault(item.entry) || item.entry.id === "topmodul-00067-labeler-encoder-feedback"));
      if (!eligible.length) return;
      const input = eligible.map((item) => item.entry.id === "topmodul-00067-labeler-encoder-feedback" ? "00067" : entryCode(item.entry)).join(", ");
      let inherited;
      try { inherited = base.analyzeTopModulFaultStack(input, context); } catch (_) { inherited = null; }
      if (!inherited) return;
      const byId = new Map(observed.map((item) => [item.entry.id, item]));
      for (const source of inherited.observed || []) {
        const target = byId.get(source.entry.id);
        if (!target) continue;
        target.upstreamCandidatesInStack.push(...(source.upstreamCandidatesInStack || []).map((row) => Object.freeze({ ...row, code: row.code || (Number.isFinite(Number(row.number)) ? String(row.number).padStart(3, "0") : "") })));
        target.downstreamItemsSupported.push(...(source.downstreamItemsSupported || []).map((row) => Object.freeze({ ...row, code: row.code || (Number.isFinite(Number(row.number)) ? String(row.number).padStart(3, "0") : "") })));
        target.relatedInStack.push(...(source.relatedInStack || []).map((row) => Object.freeze({ ...row, code: row.code || (Number.isFinite(Number(row.number)) ? String(row.number).padStart(3, "0") : "") })));
      }
    }

    function addWarningRelations(observed) {
      const byCode = new Map(observed.map((item) => [String(item.entry.code || ""), item]));
      for (const item of observed) {
        if (!isWarning(item.entry)) continue;
        const link = WARNING_LINKS[Number(item.entry.warningNumber)];
        if (!link) continue;
        const downstream = byCode.get(link.targetCode);
        if (!downstream) continue;
        item.downstreamItemsSupported.push(Object.freeze({
          code: downstream.entry.code,
          number: Number(downstream.entry.number),
          observedIndex: downstream.observedIndex,
          title: downstream.entry.title,
          relationKind: link.kind,
          reason: link.reason
        }));
        downstream.upstreamCandidatesInStack.push(Object.freeze({
          code: item.entry.code,
          warningNumber: item.entry.warningNumber,
          observedIndex: item.observedIndex,
          title: item.entry.title,
          appearedEarlier: item.observedIndex < downstream.observedIndex,
          relationKind: link.kind,
          reason: link.reason
        }));
      }
    }

    function analyzeTopModulFaultStack(input, context = {}) {
      const tokens = extractMixedTokens(input);
      const observed = [];
      const unresolved = [];
      const seen = new Set();

      tokens.forEach((token, tokenIndex) => {
        const entry = resolveToken(token, context);
        if (!entry) {
          unresolved.push(Object.freeze({ token: String(token), observedIndex: tokenIndex }));
          return;
        }
        const key = String(entry.id || `${entry.code}:${entry.title}`);
        if (seen.has(key)) return;
        seen.add(key);
        const classification = classify(entry, token, context);
        observed.push({
          entry,
          token: String(token),
          observedIndex: observed.length,
          ...classification,
          upstreamCandidatesInStack: [],
          downstreamItemsSupported: [],
          relatedInStack: []
        });
      });

      copyBaseRelations(observed, context);
      addWarningRelations(observed);

      const immutableObserved = observed.map((item) => Object.freeze({
        ...item,
        upstreamCandidatesInStack: Object.freeze([...item.upstreamCandidatesInStack]),
        downstreamItemsSupported: Object.freeze([...item.downstreamItemsSupported]),
        relatedInStack: Object.freeze([...item.relatedInStack])
      }));

      const recommended = immutableObserved.map((item) => {
        const supportAdjustment = Math.min(12, item.downstreamItemsSupported.length * 4);
        const sourceGapPenalty = ["source-gap", "disabled", "catalog-only", "warning-source-gap"].includes(item.role) ? 8 : 0;
        return Object.freeze({ ...item, investigationScore: Math.max(0, Number(item.priority || 82) - supportAdjustment + sourceGapPenalty) });
      }).sort((a, b) => a.investigationScore - b.investigationScore || a.observedIndex - b.observedIndex);

      const earliest = immutableObserved[0] || null;
      const strongest = recommended[0] || null;
      const warningCount = immutableObserved.filter((item) => isWarning(item.entry)).length;
      const directCount = immutableObserved.filter((item) => ["direct-producer", "verified-producer", "field-observed", "cart-fault"].includes(item.role)).length;
      const summaryCount = immutableObserved.filter((item) => ["downstream-summary", "supervision", "escalation"].includes(item.role)).length;
      const gapCount = immutableObserved.filter((item) => ["source-gap", "disabled", "catalog-only", "warning-source-gap"].includes(item.role)).length;

      return Object.freeze({
        input: String(input || ""),
        observed: Object.freeze(immutableObserved),
        recommended: Object.freeze(recommended),
        unresolved: Object.freeze(unresolved),
        chronologyAgreement: Boolean(earliest && strongest && earliest.entry.id === strongest.entry.id),
        earliestObserved: earliest,
        strongestEvidence: strongest,
        counts: Object.freeze({ resolved: immutableObserved.length, direct: directCount, summaries: summaryCount, warnings: warningCount, gaps: gapCount, unresolved: unresolved.length }),
        guidance: "Observed HMI order is preserved exactly across Cart warnings, Cart-local faults, field HMI codes, and base-Labeler PLC faults. Source-backed warnings can provide pre-fault/state context, but they do not prove causality by themselves. Use a warning-to-fault relationship only where the supplied source explicitly supports that progression or companion state."
      });
    }

    function validate() {
      const current = base.validate();
      const errors = [...(current.errors || [])];
      const lowLabels = analyzeTopModulFaultStack("W 0005 → 00025");
      if (lowLabels.observed[0]?.entry?.id !== "apl-cart-warning-0005" || lowLabels.observed[1]?.entry?.code !== "00025") errors.push("v366 lost W 0005 -> Cart 00025 mixed chronology.");
      if (lowLabels.observed[0]?.role !== "pre-fault-warning") errors.push("W 0005 must remain pre-fault warning evidence.");
      if (!lowLabels.observed[0]?.downstreamItemsSupported?.some((row) => row.code === "00025")) errors.push("W 0005 lost its source-backed 00025 progression link.");
      const labelLength = analyzeTopModulFaultStack("W0012, 00022");
      if (!labelLength.observed[0]?.downstreamItemsSupported?.some((row) => row.code === "00022")) errors.push("W 0012 lost its source-backed 00022 escalation link.");
      const communication = analyzeTopModulFaultStack("W 0015, 00014");
      if (!communication.observed[0]?.downstreamItemsSupported?.some((row) => row.code === "00014")) errors.push("W 0015 lost its Cart 00014 companion relationship.");
      const warningGap = analyzeTopModulFaultStack("W 0002, 00016");
      if (warningGap.observed[0]?.role !== "warning-source-gap") errors.push("W 0002 must remain a warning source gap.");
      const namespaces = analyzeTopModulFaultStack("W 0005, 00005, 005");
      if (namespaces.observed[0]?.entry?.id !== "apl-cart-warning-0005" || namespaces.observed[1]?.entry?.code !== "00005" || namespaces.observed[2]?.entry?.code !== "005") errors.push("v366 mixed stack collapsed warning/Cart/base namespaces.");
      const existing = analyzeTopModulFaultStack("663, 1091");
      if (existing.recommended[0]?.entry?.number !== 1091) errors.push("v366 must preserve existing base-Labeler first-fault ranking.");
      return { ok: errors.length === 0, errors };
    }

    return Object.freeze({
      ...base,
      version: `${base.version}+apl-cart-warning-stack-v366`,
      analyzeTopModulFaultStack,
      topModulAlarmStackRoles: ROLE_LABELS,
      aplCartWarningStackLinks: WARNING_LINKS,
      validate
    });
  };
});